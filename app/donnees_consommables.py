def code_site(site):
    """Renvoie le code d'un site (1001 ALEM bouira, …) ou '' s'il est inconnu."""
    if not site:
        return ""
    texte = (
        str(site)
        .strip()
        .lower()
        .replace("'", "")
        .replace("\u2019", "")
        .replace(" ", "")
    )
    for cle in (
        "ainbessem",
        "ainbessam",
        "lakhdaria",
        "mched",
        "meched",
        "ghozlane",
        "bordj",
        "bouira",
        "sour",
        "seg",
    ):
        if cle in texte:
            return CODES_SITES[cle]
    return ""


def site_code(site):
    """Renvoie « 1001 ALEM bouira » (code suivi du nom) ou le nom seul si inconnu."""
    if not site:
        return ""
    code = code_site(site)
    return (code + " " + str(site)) if code else str(site)
